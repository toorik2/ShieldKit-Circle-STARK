function prettyCanonicalJson(value: unknown): string {
  return `${JSON.stringify(JSON.parse(canonicalV17Json(value)), null, 2)}\n`;
}

function typescriptLayout(graph: V17ConstructionGraph, protocolIdHex: string): string {
  const frames = graph.proof.frames.map((frame) => ({
    id: frame.id,
    offsetBytes: frame.offsetBytes,
    itemBytes: frame.itemBytes,
    itemCount: frame.itemCount,
    totalBytes: frame.itemBytes * frame.itemCount,
    codec: frame.codec,
  }));
  return `// Generated by scripts/generate-v17-construction.ts. Do not edit.\n` +
    `export const V17_GENERATED_PROOF_VERSION = ${V17_PROOF_VERSION} as const;\n` +
    `export const V17_GENERATED_PROTOCOL_ID_HEX = ${JSON.stringify(protocolIdHex)} as const;\n` +
    `export const V17_GENERATED_FOUNDATION = ${JSON.stringify(graph.foundation, null, 2)} as const;\n` +
    `export const V17_GENERATED_FIXED_PREFIX_BYTES = ${graph.proof.dynamicTail.offsetBytes} as const;\n` +
    `export const V17_GENERATED_DYNAMIC_TAIL = ${JSON.stringify(graph.proof.dynamicTail, null, 2)} as const;\n` +
    `export const V17_GENERATED_PROOF_FRAMES = ${JSON.stringify(frames, null, 2)} as const;\n` +
    `export const V17_GENERATED_TRANSCRIPT_PHASES = ${JSON.stringify(graph.transcript, null, 2)} as const;\n` +
    `export const V17_GENERATED_COMMITMENTS = ${JSON.stringify(graph.commitments, null, 2)} as const;\n` +
    `export const V17_GENERATED_FRI_FOLD_LOGS = ${JSON.stringify(graph.foundation.friFoldLogs)} as const;\n` +
    `export const V17_GENERATED_FRI_FOLD_CHALLENGE_COUNTS = ${JSON.stringify(graph.foundation.friFoldChallengeCounts)} as const;\n` +
    `export const V17_GENERATED_ELASTIC_PREFIX_SCALE = ${V17_ELASTIC_PREFIX_SCALE} as const;\n` +
    `export const V17_GENERATED_MAXIMUM_PROOF_BYTES = ${V17_MAXIMUM_CANONICAL_PROOF_BYTES} as const;\n` +
    `export const V17_GENERATED_ALLOCATION_POLICY = ${JSON.stringify(graph.allocation, null, 2)} as const;\n` +
    `export const V17_GENERATED_ROM_POLICY = ${JSON.stringify(graph.rom, null, 2)} as const;\n`;
}

function rustIdentifier(value: string): string {
  return value.replaceAll(/[^A-Za-z0-9]/g, "_").toUpperCase();
}

function rustLayout(graph: V17ConstructionGraph, protocolIdHex: string): string {
  const protocolBytes = Array.from(Buffer.from(protocolIdHex, "hex"), (byte) => `0x${byte.toString(16).padStart(2, "0")}`);
  const frameRows = graph.proof.frames.map((frame) =>
    `    ProofFrame { id: ${JSON.stringify(frame.id)}, offset_bytes: ${frame.offsetBytes}, item_bytes: ${frame.itemBytes}, item_count: ${frame.itemCount} },`)
    .join("\n");
  const frameConstants = graph.proof.frames.map((frame) =>
    `pub const ${rustIdentifier(frame.id)}_OFFSET: usize = ${frame.offsetBytes};`)
    .join("\n");
  const roundRows = graph.foundation.roundGrinding.map((round) =>
    `    RoundGrinding { id: ${JSON.stringify(round.id)}, bits: ${round.bits} },`)
    .join("\n");
  const merkleRows = graph.commitments.map((commitment) =>
    `    MerkleCommitment { id: ${JSON.stringify(commitment.id)}, label: ${JSON.stringify(commitment.hashLabel)}, log_rows: ${commitment.domainLog}, row_bytes: ${commitment.rowBytes}, leaf_shards: ${commitment.leafShards}, quartet_first: ${commitment.arities[0] === 4}, verifier_cuts: &[${commitment.verifierCuts.join(", ")}] },`)
    .join("\n");
  return `// Generated by scripts/generate-v17-construction.ts. Do not edit.\n` +
    `pub const V17_PROOF_VERSION: u8 = ${V17_PROOF_VERSION};\n` +
    `pub const V17_RELATION_CONSTRUCTION_VERSION: u8 = ${graph.foundation.relationConstructionVersion};\n` +
    `pub const V17_PROTOCOL_ID: [u8; 32] = [${protocolBytes.join(", ")}];\n` +
    `pub const V17_FIXED_PREFIX_BYTES: usize = ${graph.proof.dynamicTail.offsetBytes};\n` +
    `pub const V17_RELATION_LOG: u8 = ${graph.foundation.relationLog};\n` +
    `pub const V17_FUNCTION_DEGREE_LOG: u8 = ${graph.foundation.functionDegreeLog};\n` +
    `pub const V17_QUOTIENT_DEGREE_LOG: u8 = ${graph.foundation.quotientDegreeLog};\n` +
    `pub const V17_EVALUATION_LOG: u8 = ${graph.foundation.evaluationLog};\n` +
    `pub const V17_QUERIES: usize = ${graph.foundation.queries};\n` +
    `pub const V17_OOD_VALUE_COUNT: usize = ${graph.foundation.oodValueCount};\n` +
    `pub const V17_DEGREE_CORRECTED_BATCH_WIDTH: usize = ${graph.foundation.degreeCorrectedBatchWidth};\n` +
    `pub const V17_GRINDING_NONCE_BYTES: usize = ${graph.foundation.grindingNonce.serializedBytes};\n` +
    `pub const V17_ELASTIC_PREFIX_SCALE: usize = ${V17_ELASTIC_PREFIX_SCALE};\n` +
    `pub const V17_MAXIMUM_PROOF_BYTES: usize = ${V17_MAXIMUM_CANONICAL_PROOF_BYTES};\n` +
    `pub const V17_OPCOST_PER_INPUT_BYTE: usize = ${graph.rom.limits.opcostPerInputByte};\n` +
    `pub const V17_MAX_SCRIPT_BYTES: usize = ${graph.rom.limits.scriptBytes};\n` +
    `pub const V17_MAX_FUNCTION_IDENTIFIER_BYTES: usize = ${graph.rom.limits.functionIdentifierBytes};\n` +
    `pub const V17_CONSENSUS_TX_BYTES: usize = ${graph.rom.limits.consensusTransactionBytes};\n` +
    `pub const V17_FRI_FOLD_LOGS: &[u8] = &[${graph.foundation.friFoldLogs.join(", ")}];\n\n` +
    `pub const V17_FRI_FOLD_CHALLENGE_COUNTS: &[u8] = &[${graph.foundation.friFoldChallengeCounts.join(", ")}];\n\n` +
    `#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n` +
    `pub struct RoundGrinding {\n` +
    `    pub id: &'static str,\n` +
    `    pub bits: u8,\n` +
    `}\n\n` +
    `pub const V17_ROUND_GRINDING: &[RoundGrinding] = &[\n${roundRows}\n];\n\n` +
    `#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n` +
    `pub struct MerkleCommitment {\n` +
    `    pub id: &'static str,\n` +
    `    pub label: &'static str,\n` +
    `    pub log_rows: u8,\n` +
    `    pub row_bytes: usize,\n` +
    `    pub leaf_shards: u8,\n` +
    `    pub quartet_first: bool,\n` +
    `    pub verifier_cuts: &'static [u8],\n` +
    `}\n\n` +
    `pub const V17_MERKLE_COMMITMENTS: &[MerkleCommitment] = &[\n${merkleRows}\n];\n\n` +
    `#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n` +
    `pub struct ProofFrame {\n` +
    `    pub id: &'static str,\n` +
    `    pub offset_bytes: usize,\n` +
    `    pub item_bytes: usize,\n` +
    `    pub item_count: usize,\n` +
    `}\n\n` +
    `${frameConstants}\n\n` +
    `pub const V17_PROOF_FRAMES: &[ProofFrame] = &[\n${frameRows}\n];\n`;
}

function roleSemanticObject(
  kind: string,
  properties: Readonly<Record<string, unknown>> = {},
  required: readonly string[] = [],
): unknown {
  return {
    type: "object",
    additionalProperties: false,
    required: ["kind", ...required],
    properties: { kind: { const: kind }, ...properties },
  };
}

function roleSemanticSchema(): unknown {
  const index = { type: "integer", minimum: 0 };
  const matrix = { enum: V17_MATRIX_NAMES };
  return {
    oneOf: [
      roleSemanticObject("settlement"),
      roleSemanticObject("ood-air"),
      roleSemanticObject("batch-link-query", { query: index }, ["query"]),
      roleSemanticObject("public-boundary-inverses"),
      roleSemanticObject("proof-header"),
      roleSemanticObject("edge-append"),
      roleSemanticObject("sparse-nullifier", {
        root: { enum: ["absence", "used"] }, segment: { enum: [0, 1] },
      }, ["root", "segment"]),
      roleSemanticObject("public-boundary-sum"),
      roleSemanticObject("transcript", {
        part: { enum: V17_TRANSCRIPT_ROLE_PARTS },
      }, ["part"]),
      roleSemanticObject("query-schedule"),
      roleSemanticObject("opening-current"),
      roleSemanticObject("opening-global", {
        stage: { enum: ["current", "previous", "shape"] },
      }, ["stage"]),
      roleSemanticObject("opening-fri", {
        layer: index, stage: { const: "current" }, mappingShard: { enum: [0, 1] },
      }, ["layer", "stage", "mappingShard"]),
      roleSemanticObject("opening-fri", {
        layer: index, stage: { const: "shape" },
      }, ["layer", "stage"]),
      roleSemanticObject("fri-fold-query", { query: index }, ["query"]),
      roleSemanticObject("matrix-merkle-leaf", {
        matrix, shard: index, shards: { enum: [1, 2] },
      }, ["matrix", "shard", "shards"]),
      roleSemanticObject("matrix-merkle-parent", {
        matrix, stage: index,
      }, ["matrix", "stage"]),
      roleSemanticObject("fri-merkle-leaf", {
        layer: index, shard: index, shards: { enum: [1, 2] },
      }, ["layer", "shard", "shards"]),
      roleSemanticObject("fri-merkle-parent", {
        layer: index, stage: index,
      }, ["layer", "stage"]),
    ],
  };
}

