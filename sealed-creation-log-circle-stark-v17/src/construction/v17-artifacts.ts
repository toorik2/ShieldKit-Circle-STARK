/**
 * Compile the emitted Draft 2020-12 schema and validate the emitted plan.
 * This is a schema-conformance gate, not a substitute for graph validation.
 */
export function assertV17VerifierPlanConformsToSchema(args: {
  readonly plan: unknown;
  readonly schema: unknown;
}): void {
  const ajv = new Ajv2020({ allErrors: true, strict: true });
  const validate = ajv.compile(args.schema as object);
  if (!validate(args.plan)) {
    throw new Error(`v17 verifier plan schema: ${ajv.errorsText(validate.errors, {
      separator: "; ",
    })}`);
  }
  const pages = (args.plan as {
    readonly rom: {
      readonly pages: readonly { readonly index: number; readonly functionIds: readonly string[] }[];
    };
  }).rom.pages;
  const seenFunctionIds = new Set<string>();
  for (const page of pages) {
    let previous: string | undefined;
    for (const functionId of page.functionIds) {
      if (seenFunctionIds.has(functionId)) {
        throw new Error(`v17 verifier plan duplicate ROM function id ${functionId}`);
      }
      if (previous !== undefined) {
        const order = previous.length - functionId.length ||
          (previous < functionId ? -1 : previous > functionId ? 1 : 0);
        if (order >= 0) {
          throw new Error(`v17 verifier plan noncanonical ROM function id order at page ${page.index}`);
        }
      }
      seenFunctionIds.add(functionId);
      previous = functionId;
    }
  }
}

/** Fail closed before generation or qualification if graph-derived artifacts disagree. */
export function assertV17VerifierPlanSchemaConsistency(
  graph: V17ConstructionGraph = V17_CONSTRUCTION_GRAPH,
): void {
  assertV17VerifierPlanConformsToSchema({
    plan: buildV17VerifierPlan(graph),
    schema: buildV17VerifierPlanSchema(graph),
  });
}

/** Pure generation: callers choose whether to check or write these bytes. */
export function generateV17ConstructionArtifacts(
  graph: V17ConstructionGraph = V17_CONSTRUCTION_GRAPH,
): V17GeneratedArtifacts {
  validateV17ConstructionGraph(graph);
  const protocolIdHex = v17ProtocolIdHex(graph);
  const plan = buildV17VerifierPlan(graph);
  const planSchema = buildV17VerifierPlanSchema(graph);
  assertV17VerifierPlanConformsToSchema({ plan, schema: planSchema });
  const qualification = createPendingV17Qualification(protocolIdHex);
  return {
    "src/construction/generated/v17-layout.ts": typescriptLayout(graph, protocolIdHex),
    "src/construction/generated/v17-layout.rs": rustLayout(graph, protocolIdHex),
    "src/construction/generated/v17-verifier-plan.json": prettyCanonicalJson(plan),
    "src/construction/generated/v17-verifier-plan.schema.json": prettyCanonicalJson(planSchema),
    "src/construction/generated/v17-qualification.json": prettyCanonicalJson(qualification),
  };
}
